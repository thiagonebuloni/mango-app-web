import {
  generateRuleBasedReport,
  LOCAL_AI_MODEL_ID,
  updateLocalAiStatus,
  type LocalAiReportRequest,
} from './local-ai';

export type IAProviderName = 'transformersjs';

export interface IAReportResult {
  text: string;
  provider: IAProviderName;
}

type ProgressCallback = (progress: number) => void;

async function createModel(onProgress: ProgressCallback) {
  const { pipeline } = await import('@huggingface/transformers');
  return pipeline('text2text-generation', LOCAL_AI_MODEL_ID, {
    progress_callback: (info) => {
      if (info.status === 'progress_total' && info.total > 0) {
        onProgress(Math.round(info.progress));
      }
    },
  });
}

let modelPromise: ReturnType<typeof createModel> | null = null;

async function getModel(onProgress: ProgressCallback) {
  if (!modelPromise) {
    updateLocalAiStatus({
      available: false,
      loading: true,
      reason: 'model-loading',
    });
    modelPromise = createModel(onProgress)
      .then((model) => {
        updateLocalAiStatus({
          available: true,
          loading: false,
          reason: 'model-ready',
        });
        return model;
      })
      .catch((error: unknown) => {
        modelPromise = null;
        updateLocalAiStatus({
          available: false,
          loading: false,
          reason: 'model-error',
        });
        throw error;
      });
  }

  return modelPromise;
}

function criarPrompt(request: LocalAiReportRequest): string {
  const pt = request.locale === 'pt-BR';
  const currency = new Intl.NumberFormat(request.locale, {
    style: 'currency',
    currency: request.locale === 'pt-BR' ? 'BRL' : 'USD',
  });
  const categories = (request.categoryBreakdown ?? [])
    .map(({ name, cents }) => `${name}: ${currency.format(cents / 100)}`)
    .join('; ');
  const previous = request.previousPeriod
    ? pt
      ? ` Período anterior: despesas ${currency.format(request.previousPeriod.expensesCents / 100)} e receitas ${currency.format(request.previousPeriod.incomeCents / 100)}.`
      : ` Previous period: expenses ${currency.format(request.previousPeriod.expensesCents / 100)} and income ${currency.format(request.previousPeriod.incomeCents / 100)}.`
    : '';

  return pt
    ? `Escreva duas frases curtas em português do Brasil sobre estes dados financeiros agregados. Use somente fatos fornecidos, não invente valores e não dê aconselhamento profissional. Despesas: ${currency.format(request.expensesCents / 100)}. Receitas: ${currency.format(request.incomeCents / 100)}. Categorias de despesas: ${categories || 'sem despesas por categoria'}.${previous}`
    : `Write two short sentences in English about these aggregated financial data. Use only facts provided, do not invent values, and do not give professional advice. Expenses: ${currency.format(request.expensesCents / 100)}. Income: ${currency.format(request.incomeCents / 100)}. Expense categories: ${categories || 'no categorized expenses'}.${previous}`;
}

export const iaReportService = {
  async generateReport(
    request: LocalAiReportRequest,
    onProgress: ProgressCallback = () => {},
  ): Promise<IAReportResult> {
    const model = await getModel(onProgress);
    const [result] = await model(criarPrompt(request), {
      max_new_tokens: 96,
      do_sample: false,
    });
    const insight = result?.generated_text.trim();
    if (!insight) {
      throw new Error(
        request.locale === 'pt-BR'
          ? 'O modelo local não gerou uma análise.'
          : 'The local model did not generate an analysis.',
      );
    }

    const pt = request.locale === 'pt-BR';
    const lines = generateRuleBasedReport(request);
    const disclaimer = lines.splice(-2);
    lines.push(
      '',
      pt ? 'ANÁLISE GERADA PELO MODELO LOCAL' : 'ANALYSIS GENERATED BY THE LOCAL MODEL',
      insight,
      '',
      ...disclaimer,
    );

    return {
      text: lines.join('\n'),
      provider: 'transformersjs',
    };
  },
};
