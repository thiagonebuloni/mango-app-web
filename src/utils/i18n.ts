export function traduzir(texto: string, idioma: Idioma): string {
  return idioma === 'en-US' ? (traducoesEn[texto] ?? texto) : texto;
}

export function useI18n() {
  const idioma = useMangoStore((state) => state.idioma);
  return {
    idioma,
    t: (texto: string) => traduzir(texto, idioma),
  };
}
